import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";
import { pickBriefing } from "./render-pages.mjs";

const root = join(import.meta.dirname, "..");

function read(path) {
  return readFileSync(join(root, path), "utf8");
}

function walk(dir, found = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, found);
    else found.push(path);
  }
  return found;
}

function nodes(html) {
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">\s*([\s\S]*?)\s*<\/script>/g)];
  assert.ok(blocks.length >= 1);
  return blocks.flatMap((block) => {
    const data = JSON.parse(block[1]);
    return Array.isArray(data["@graph"]) ? data["@graph"] : [data];
  });
}

function meta(html, name) {
  const found = html.match(new RegExp(`<meta name="${name}" content="([^"]*)"`));
  assert.ok(found, name);
  return found[1];
}

function visibleFaq(html) {
  const start = html.indexOf('id="faq"');
  const slice = html.slice(start);
  const questions = [...slice.matchAll(/<summary><h3>([^<]*)<\/h3><\/summary>\s*<p class="prose">([\s\S]*?)<\/p>/g)];
  return questions.map((match) => ({
    name: match[1],
    text: match[2].replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim()
  }));
}

test("rendered pages stay in sync with the feeds", () => {
  const check = spawnSync(process.execPath, ["scripts/render-pages.mjs", "--check"], {
    cwd: root,
    encoding: "utf8"
  });
  assert.equal(check.status, 0, `${check.stdout}\n${check.stderr}`);
});

test("every pulse item has a German and an English article", () => {
  const pulse = JSON.parse(read("pulse.json"));
  const items = Array.isArray(pulse) ? pulse : pulse.items;
  const sitemap = read("docs/sitemap.xml");
  for (const item of items) {
    const slug = item.id.replace(/^pulse-/, "");
    for (const [locale, dir] of [["de", "docs/briefing"], ["en", "docs/en/briefing"]]) {
      const rel = `${dir}/${slug}/index.html`;
      assert.equal(existsSync(join(root, rel)), true, rel);
      const html = read(rel);
      assert.match(html, /generated by scripts\/render-pages\.mjs/);
      assert.equal((html.match(/<h1>/g) || []).length, 1, rel);
      assert.ok(meta(html, "description").length <= 160, rel);
      const article = nodes(html).find((node) => node["@type"] === "Article");
      assert.ok(article, rel);
      assert.equal(article.inLanguage, locale);
      assert.equal(article.datePublished, String(item.date).slice(0, 10));
      assert.equal(article.publisher.name, "Sapaude");
      assert.equal(article.author.name, "Sapaude");
      assert.equal(article.citation, item.source.url);
      assert.match(html, new RegExp(`rel="canonical" href="https://sapaude\\.app/${locale === "en" ? "en/" : ""}briefing/${slug}/"`));
      assert.match(html, /hreflang="de"/);
      assert.match(html, /hreflang="en"/);
      assert.match(html, /hreflang="x-default"/);
      assert.doesNotMatch(html, /Niklas|Neuburger|Karlshuld|niklas\.galli/);
      assert.doesNotMatch(html, /aggregateRating/);
    }
    assert.match(sitemap, new RegExp(`https://sapaude\\.app/briefing/${slug}/`));
    assert.match(sitemap, new RegExp(`https://sapaude\\.app/en/briefing/${slug}/`));
  }
});

test("homepage cards match the briefing filter", () => {
  const briefing = JSON.parse(read("briefing.json"));
  const day = briefing.days[0];
  for (const [locale, path] of [["de", "docs/index.html"], ["en", "docs/en/index.html"]]) {
    const html = read(path);
    const picked = pickBriefing(day, locale);
    assert.equal(picked.length, 3);
    const cards = html.slice(html.indexOf("<!-- briefing:cards -->"), html.indexOf("<!-- /briefing:cards -->"));
    for (const item of picked) {
      const copy = locale === "de" && item.i18n && item.i18n.de ? item.i18n.de : item;
      assert.match(cards, new RegExp(copy.headline.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")));
    }
    assert.match(html, new RegExp(`data-briefing-date datetime="${day.date}"`));
  }
});

test("homepage FAQ schema matches the visible questions", () => {
  for (const path of ["docs/index.html", "docs/en/index.html"]) {
    const html = read(path);
    const visible = visibleFaq(html);
    assert.equal(visible.length, 8, path);
    const faq = nodes(html).find((node) => node["@type"] === "FAQPage");
    assert.equal(faq.mainEntity.length, 8, path);
    faq.mainEntity.forEach((question, index) => {
      assert.equal(question.name, visible[index].name, path);
      assert.equal(question.acceptedAnswer.text.replace(/\s+/g, " ").trim(), visible[index].text, path);
    });
    assert.doesNotMatch(html, /aggregateRating|downloadUrl|sameAs/);
    const logo = nodes(html).find((node) => node["@type"] === "Organization").logo;
    assert.equal(logo.url, "https://sapaude.app/logo-512.png");
    assert.equal(logo.width, 512);
    assert.equal(logo.height, 512);
  }
  assert.match(read("docs/index.html"), /Es gibt nicht die eine App für alle\./);
  assert.match(read("docs/index.html"), /<title>Sapaude — KI lernen wie eine Sprache, ab 5 Minuten am Tag<\/title>/);
  assert.equal(meta(read("docs/index.html"), "description").length, 160);
  assert.equal(meta(read("docs/en/index.html"), "description").length, 148);
});

test("logo is a square PNG of at least 112 pixels", () => {
  const buf = readFileSync(join(root, "docs/logo-512.png"));
  assert.equal(buf.toString("ascii", 1, 4), "PNG");
  assert.equal(buf.readUInt32BE(16), 512);
  assert.equal(buf.readUInt32BE(20), 512);
});

test("new public pages do not carry the personal name", () => {
  const pages = walk(join(root, "docs")).filter((path) => path.endsWith(".html") || path.endsWith("llms.txt"));
  for (const path of pages) {
    const rel = path.slice(root.length + 1);
    if (rel === "docs/impressum/index.html") continue;
    const html = read(rel);
    assert.doesNotMatch(html, /Niklas|Neuburger|Karlshuld|niklas\.galli@/, rel);
  }
});

test("guide pages and soft redirects are crawlable without store fiction", () => {
  for (const rel of [
    "docs/ki-lernen-app/index.html",
    "docs/duolingo-fuer-ki/index.html",
    "docs/en/best-app-to-learn-ai/index.html",
    "docs/en/duolingo-for-ai/index.html",
    "docs/ueber/index.html",
    "docs/en/about/index.html"
  ]) {
    const html = read(rel);
    assert.equal((html.match(/<h1>/g) || []).length, 1, rel);
    assert.ok(meta(html, "description").length <= 160, rel);
    assert.match(html, /rel="canonical"/);
    assert.match(html, /hreflang="x-default" href="https:\/\/sapaude\.app\//);
    assert.doesNotMatch(html, /apps\.apple\.com|play\.google\.com|aggregateRating/);
    assert.match(html, /support@sapaude\.app/);
  }
  const sitemap = read("docs/sitemap.xml");
  assert.match(sitemap, /https:\/\/sapaude\.app\/duolingo-fuer-ki\//);
  assert.match(sitemap, /https:\/\/sapaude\.app\/en\/duolingo-for-ai\//);
  assert.match(sitemap, /https:\/\/sapaude\.app\/briefing\/tag\/2026-11-14\//);
  assert.doesNotMatch(sitemap, /https:\/\/sapaude\.app\/blog\//);
  assert.doesNotMatch(sitemap, /https:\/\/sapaude\.app\/de\//);
  assert.match(read("docs/de/privacy/index.html"), /http-equiv="refresh" content="0; url=\/privacy\/"/);
  assert.match(read("docs/about/index.html"), /http-equiv="refresh" content="0; url=\/ueber\/"/);
  assert.match(read("docs/llms.txt"), /sapere aude/i);
  assert.match(read("docs/llms.txt"), /https:\/\/sapaude\.app\/briefing\//);
  assert.doesNotMatch(read("docs/index.html"), /Sapere aude/);
  assert.doesNotMatch(read("docs/en/index.html"), /Sapere aude/);
});
